package com.worklyindia.aivoice

import android.app.Activity
import android.app.AlertDialog
import android.content.Intent
import android.os.Bundle
import android.view.ViewGroup
import android.widget.Button
import android.widget.EditText
import android.widget.LinearLayout
import android.widget.ScrollView
import android.widget.TextView
import android.widget.Toast
import java.text.DateFormat
import java.util.Date
import java.util.UUID

/**
 * Offline task-planning foundation plus a small, explicit allowlist of reversible
 * Android navigation actions. Never executes free-form model output.
 */
class ChatWorkAgentActivity : Activity() {
    private val prefs by lazy { getSharedPreferences("chatwork_agent_audit", MODE_PRIVATE) }
    private lateinit var content: LinearLayout
    private var pendingGoal = ""
    private var pendingSteps: List<String> = emptyList()

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        val root = LinearLayout(this).apply {
            orientation = LinearLayout.VERTICAL
            setPadding(24, 24, 24, 24)
        }
        root.addView(TextView(this).apply { text = "AI Agent"; textSize = 24f })
        root.addView(TextView(this).apply {
            text = "Create an offline task plan, or choose a supported phone action. Every action is previewed and requires your confirmation."
            setPadding(0, 12, 0, 16)
        })
        val goal = EditText(this).apply {
            hint = "What would you like the agent to plan?"
            minLines = 2
            maxLines = 4
        }
        root.addView(goal)
        val buttons = LinearLayout(this).apply { orientation = LinearLayout.HORIZONTAL }
        buttons.addView(Button(this@ChatWorkAgentActivity).apply {
            text = "Create plan"
            isAllCaps = false
            setOnClickListener { createPlan(goal.text.toString()) }
        })
        buttons.addView(Button(this@ChatWorkAgentActivity).apply {
            text = "Safe phone actions"
            isAllCaps = false
            setOnClickListener { showSafeActions() }
        })
        buttons.addView(Button(this@ChatWorkAgentActivity).apply {
            text = "Audit history"
            isAllCaps = false
            setOnClickListener { showHistory() }
        })
        root.addView(buttons)
        content = LinearLayout(this).apply { orientation = LinearLayout.VERTICAL }
        root.addView(ScrollView(this).apply { addView(content) },
            LinearLayout.LayoutParams(ViewGroup.LayoutParams.MATCH_PARENT, 0, 1f))
        root.addView(Button(this).apply {
            text = "Back"
            isAllCaps = false
            setOnClickListener { finish() }
        })
        setContentView(root)
    }

    private fun createPlan(rawGoal: String) {
        val goal = rawGoal.trim().take(500)
        if (goal.isBlank()) {
            AlertDialog.Builder(this).setMessage("Enter a task first.")
                .setPositiveButton("OK", null).show()
            return
        }
        pendingGoal = goal
        pendingSteps = listOf(
            "Understand the goal and identify required information",
            "Prepare a proposed sequence of small, reversible actions",
            "Review permissions, privacy and possible side effects",
            "Ask for confirmation before any connected action"
        )
        content.removeAllViews()
        content.addView(TextView(this).apply {
            text = "Proposed plan for:\n" + goal + "\n\n" +
                pendingSteps.mapIndexed { index, step -> (index + 1).toString() + ". " + step }.joinToString("\n")
            textSize = 16f
            setPadding(0, 16, 0, 16)
        })
        content.addView(TextView(this).apply {
            text = "This generic plan is not generated by an LLM and does not execute any action."
        })
        content.addView(Button(this).apply {
            text = "Approve plan"
            isAllCaps = false
            setOnClickListener { approvePlan() }
        })
        content.addView(Button(this).apply {
            text = "Discard plan"
            isAllCaps = false
            setOnClickListener {
                pendingGoal = ""
                pendingSteps = emptyList()
                content.removeAllViews()
            }
        })
    }

    private fun approvePlan() {
        if (pendingGoal.isBlank() || pendingSteps.isEmpty()) return
        appendAudit("APPROVED_PLAN_ONLY", pendingGoal, "Plan saved; no action executed.")
        pendingGoal = ""
        pendingSteps = emptyList()
        content.removeAllViews()
        content.addView(TextView(this).apply {
            text = "Plan approved and saved to local audit history. No actions were executed."
            textSize = 16f
        })
    }

    private data class SafeAction(val label: String, val details: String, val intent: Intent)

    private fun showSafeActions() {
        val actions = listOf(
            SafeAction("Open Wi-Fi settings", "Opens Android Wi-Fi settings. ChatWork will not toggle Wi-Fi.", Intent(android.provider.Settings.ACTION_WIFI_SETTINGS)),
            SafeAction("Open Bluetooth settings", "Opens Android Bluetooth settings. ChatWork will not toggle Bluetooth.", Intent(android.provider.Settings.ACTION_BLUETOOTH_SETTINGS)),
            SafeAction("Open Display settings", "Opens Android Display settings. No setting is changed automatically.", Intent(android.provider.Settings.ACTION_DISPLAY_SETTINGS)),
            SafeAction("Open this app's notification settings", "Opens notification settings for ChatWork.", Intent(android.provider.Settings.ACTION_APP_NOTIFICATION_SETTINGS).putExtra(android.provider.Settings.EXTRA_APP_PACKAGE, packageName))
        ).filter { it.intent.resolveActivity(packageManager) != null }
        val labels = actions.map { it.label }.toMutableList()
        labels.add("Launch an installed app…")
        AlertDialog.Builder(this).setTitle("Choose a safe phone action")
            .setItems(labels.toTypedArray()) { _, index ->
                if (index == actions.size) chooseInstalledApp()
                else confirmAndRun(actions[index])
            }.setNegativeButton("Cancel", null).show()
    }

    private fun chooseInstalledApp() {
        val pm = packageManager
        val apps = pm.queryIntentActivities(
            Intent(Intent.ACTION_MAIN).addCategory(Intent.CATEGORY_LAUNCHER), 0
        ).filter { it.activityInfo.packageName != packageName }
            .sortedBy { it.loadLabel(pm).toString().lowercase() }
        if (apps.isEmpty()) {
            Toast.makeText(this, "No launchable apps found.", Toast.LENGTH_SHORT).show()
            return
        }
        AlertDialog.Builder(this).setTitle("Choose app to launch")
            .setItems(apps.map { it.loadLabel(pm).toString() }.toTypedArray()) { _, index ->
                val info = apps[index].activityInfo
                val launch = pm.getLaunchIntentForPackage(info.packageName)
                if (launch != null) confirmAndRun(
                    SafeAction("Launch " + info.loadLabel(pm), "Opens the selected app. ChatWork does not read its screen or enter data.", launch)
                )
            }.setNegativeButton("Cancel", null).show()
    }

    private fun confirmAndRun(action: SafeAction) {
        AlertDialog.Builder(this).setTitle("Review action")
            .setMessage(action.label + "\n\n" + action.details + "\n\nRun this action now?")
            .setNegativeButton("Cancel", null)
            .setPositiveButton("Run") { _, _ ->
                try {
                    startActivity(action.intent)
                    appendAudit("ACTION_LAUNCH_REQUESTED", action.label, "Android accepted the launch request; destination completion is not verified.")
                } catch (failure: Exception) {
                    appendAudit("ACTION_FAILED", action.label, failure.javaClass.simpleName)
                    Toast.makeText(this, "Could not open: " + action.label, Toast.LENGTH_LONG).show()
                }
            }.show()
    }

    private fun appendAudit(type: String, title: String, details: String) {
        val record = listOf(
            UUID.randomUUID().toString(),
            System.currentTimeMillis().toString(),
            type,
            title.replace("\n", " ").replace("\t", " "),
            details.replace("\n", " ").replace("\t", " ")
        ).joinToString("\t")
        val old = prefs.getString("audit", "").orEmpty()
        val updated = (listOf(record) + old.lines().filter { it.isNotBlank() }).take(100)
        prefs.edit().putString("audit", updated.joinToString("\n")).apply()
    }

    private fun showHistory() {
        val records = prefs.getString("audit", "").orEmpty().lines().filter { it.isNotBlank() }
        if (records.isEmpty()) {
            AlertDialog.Builder(this).setTitle("Agent audit history")
                .setMessage("No agent records yet.")
                .setPositiveButton("OK", null).show()
            return
        }
        val labels = records.map { line ->
            val parts = line.split('\t')
            val time = parts.getOrNull(1)?.toLongOrNull()?.let {
                DateFormat.getDateTimeInstance().format(Date(it))
            } ?: "Unknown time"
            time + " — " + parts.getOrNull(2).orEmpty() + ": " + parts.getOrNull(3).orEmpty()
        }
        AlertDialog.Builder(this).setTitle("Local agent audit history")
            .setItems(labels.toTypedArray()) { _, index ->
                val parts = records[index].split('\t')
                AlertDialog.Builder(this).setTitle(parts.getOrNull(2).orEmpty())
                    .setMessage("Action: " + parts.getOrNull(3).orEmpty() +
                        "\n\nDetails: " + parts.getOrNull(4).orEmpty())
                    .setPositiveButton("OK", null).show()
            }
            .setNeutralButton("Clear history") { _, _ ->
                AlertDialog.Builder(this).setMessage("Delete all local agent audit records?")
                    .setNegativeButton("Cancel", null)
                    .setPositiveButton("Delete") { _, _ -> prefs.edit().remove("audit").apply() }
                    .show()
            }
            .setNegativeButton("Close", null).show()
    }
}
