// =============================================================================
// Birthday greetings — Push + Telegram + Email, JOB SEEKERS + EMPLOYERS
// -----------------------------------------------------------------------------
// Runs every morning (IST) from pg_cron. Every job seeker and every employer
// whose profile
// date_of_birth falls on today's IST date, and who logged in within the last
// 30 days, gets a personal wish on all three channels:
//   push     -> very short (1 line)
//   telegram -> a few warm lines
//   email    -> full, nicely written message
//
// Wording is generated by the SAME multi-provider / multi-model AI chain the
// AI chat uses (_shared/aiChain.ts), personalised per user (name + age).
// If every provider fails, the owner's template from Owner Portal ->
// Push / Telegram / Email Templates is sent as-is, so a wish is never skipped.
// Language: full, correct English only.
// =============================================================================

import { todayIST } from "./festivalCalendar.ts";
import { BRAND_CONFIG } from "./brandConfig.ts";

const IST = "Asia/Kolkata";
const BATCH_SIZE = 20;
const BASE_URL = BRAND_CONFIG.canonicalUrl;
type Audience = "job_seeker" | "employer";
const AUDIENCES: Audience[] = ["job_seeker", "employer"];
const eventKeyFor = (audience: Audience) => `birthday_greeting_${audience}`;

interface TemplateRow {
  enabled?: boolean | null;
  title?: string | null;
  subject?: string | null;
  body?: string | null;
  button_text?: string | null;
  button_url?: string | null;
}

interface Templates {
  push: TemplateRow | null;
  telegram: TemplateRow | null;
  email: TemplateRow | null;
  buttonText: string;
  buttonUrl: string;
}

interface Composed {
  pushTitle: string;
  pushBody: string;
  telegramText: string;
  emailSubject: string;
  emailHtml: string;
  source: "ai" | "template";
}

interface Recipient {
  user_id: string;
  name: string;
  email: string | null;
  telegram_chat_id: string | null;
  telegram_ok: boolean;
  dob: string | null;
}

const escapeHtml = (v: string) =>
  v.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

const fill = (text: string, values: Record<string, string>) => {
  let out = String(text || "");
  for (const [k, v] of Object.entries(values)) {
    out = out.replace(new RegExp(`\\{\\{\\s*${k}\\s*\\}\\}`, "gi"), v);
  }
  return out.replace(/\{\{[^{}]*\}\}/g, "").replace(/[ \t]{2,}/g, " ").trim();
};

const absoluteUrl = (url?: string | null) => {
  const value = String(url || "/").trim();
  if (/^https?:\/\//i.test(value)) return value;
  return `${BASE_URL}${value.startsWith("/") ? value : `/${value}`}`;
};

function parseJsonish(text: string): any | null {
  const cleaned = text.replace(/```json/gi, "").replace(/```/g, "").trim();
  const start = cleaned.indexOf("{");
  const end = cleaned.lastIndexOf("}");
  if (start < 0 || end <= start) return null;
  try {
    return JSON.parse(cleaned.slice(start, end + 1));
  } catch {
    return null;
  }
}

function ageFrom(dob: string | null, todayIso: string): number | null {
  if (!dob) return null;
  const b = new Date(`${dob.slice(0, 10)}T00:00:00+05:30`);
  const t = new Date(`${todayIso}T00:00:00+05:30`);
  if (isNaN(b.getTime())) return null;
  let years = t.getFullYear() - b.getFullYear();
  if (years < 0 || years > 120) return null;
  return years;
}

async function loadTemplates(supabase: any, audience: Audience): Promise<Templates> {
  const get = async (table: string) => {
    const { data } = await supabase.from(table).select("*").eq("event_type", eventKeyFor(audience)).maybeSingle();
    return (data as TemplateRow) ?? null;
  };
  const [push, telegram, email] = await Promise.all([
    get("push_lifecycle_templates"),
    get("telegram_lifecycle_templates"),
    get("email_lifecycle_templates"),
  ]);
  return {
    push,
    telegram,
    email,
    buttonText: String(
      telegram?.button_text || push?.button_text || (audience === "employer" ? "Open Dashboard" : "Explore Jobs"),
    ).trim(),
    buttonUrl: absoluteUrl(
      telegram?.button_url || push?.button_url || (audience === "employer" ? "/employer/dashboard" : "/jobs"),
    ),
  };
}

// --------------------------------------------------------------- COMPOSE ----
async function composeGreeting(
  tpl: Templates,
  name: string,
  age: number | null,
): Promise<Composed> {
  // Owner-written templates are sent exactly as saved — no AI rewriting, so the
  // template values the owner sees in the portal are what goes out.
  const vars = { name, age: age === null ? "" : String(age) };

  const fallbackTitle = fill(tpl.push?.title || "🎂 Happy Birthday!", vars);
  const fallbackBody = fill(
    tpl.push?.body || `Wishing you a wonderful birthday, {{name}}! — ${BRAND_CONFIG.name}`,
    vars,
  );
  const fallbackTelegram = fill(tpl.telegram?.body || fallbackBody, vars);
  const fallbackSubject = fill(tpl.email?.subject || fallbackTitle, vars);
  const fallbackEmail = fill(tpl.email?.body || fallbackTelegram, vars);

  const emailBody = fallbackEmail;
  // Owner templates are often saved as HTML — send those as-is instead of escaping the tags.
  const emailHtml = /<\/?(p|h[1-6]|div|table|br|span|strong|a)\b/i.test(emailBody) ? emailBody : emailBody
    .split(/\n{2,}/)
    .map((p) => `<p style="margin:0 0 16px;line-height:1.7;">${escapeHtml(p.trim()).replace(/\n/g, "<br />")}</p>`)
    .join("");

  return {
    pushTitle: fallbackTitle,
    pushBody: fallbackBody,
    telegramText: fallbackTelegram,
    emailSubject: fallbackSubject,
    emailHtml,
    source: "template",
  };

}

// ---------------------------------------------------------------- SENDING ---
async function safeInvoke(supabase: any, fn: string, body: unknown) {
  try {
    const { error } = await supabase.functions.invoke(fn, { body });
    if (error) console.warn(`[birthday] ${fn} failed:`, error.message);
    return !error;
  } catch (e) {
    console.warn(`[birthday] ${fn} threw:`, e);
    return false;
  }
}

async function optedOutEmails(supabase: any): Promise<Set<string>> {
  const out = new Set<string>();
  try {
    const { data } = await supabase.from("user_settings").select("user_id").eq("email_notifications", false);
    for (const row of data ?? []) out.add(String(row.user_id));
  } catch (e) {
    console.warn("[birthday] email preference lookup failed:", e);
  }
  return out;
}

// Job seekers whose date_of_birth month/day is today (IST) and who logged in
// within the last 30 days.
async function loadBirthdayRecipients(
  supabase: any,
  todayIso: string,
  audience: Audience,
): Promise<Recipient[]> {
  const since = new Date(Date.now() - 30 * 24 * 60 * 60 * 1000).toISOString();
  const [, mm, dd] = todayIso.split("-");
  const rows: any[] = [];
  let from = 0;
  const page = 1000;
  while (true) {
    const { data, error } = await supabase
      .from("profiles")
      .select("user_id, full_name, email, telegram_chat_id, telegram_notifications_enabled, date_of_birth, last_login_at")
      .not("user_id", "is", null)
      .not("date_of_birth", "is", null)
      .gte("last_login_at", since)
      .range(from, from + page - 1);
    if (error) {
      console.warn("[birthday] profile lookup failed:", error.message);
      break;
    }
    rows.push(...(data ?? []));
    if (!data || data.length < page) break;
    from += page;
  }

  const todays = rows.filter((r) => {
    const dob = String(r.date_of_birth || "").slice(0, 10);
    return dob.slice(5, 7) === mm && dob.slice(8, 10) === dd;
  });
  if (todays.length === 0) return [];

  // A single login can hold BOTH a job seeker profile and a company. Each side
  // is loaded separately with its own name / email / Telegram chat, so that
  // person receives the job-seeker wish AND the employer wish.
  const { data: companyRows } = await supabase
    .from("companies")
    .select("user_id, company_name, email, telegram_chat_id, telegram_notifications_enabled")
    .in("user_id", todays.map((r: any) => String(r.user_id)));
  const companies = new Map<string, any>();
  for (const c of companyRows ?? []) companies.set(String(c.user_id), c);

  const out: Recipient[] = [];
  for (const r of todays) {
    const id = String(r.user_id);
    const company = companies.get(id);
    if (audience === "employer") {
      if (!company) continue;
      const useCompanyTelegram = Boolean(company.telegram_chat_id);
      out.push({
        user_id: id,
        name: String(company.company_name || r.full_name || "there").trim(),
        email: (company.email || r.email) ? String(company.email || r.email) : null,
        telegram_chat_id: (company.telegram_chat_id || r.telegram_chat_id)
          ? String(company.telegram_chat_id || r.telegram_chat_id)
          : null,
        telegram_ok: useCompanyTelegram
          ? company.telegram_notifications_enabled !== false
          : r.telegram_notifications_enabled !== false,
        dob: r.date_of_birth ? String(r.date_of_birth) : null,
      });
      continue;
    }
    out.push({
      user_id: id,
      name: String(r.full_name || "there").trim(),
      email: r.email ? String(r.email) : null,
      telegram_chat_id: r.telegram_chat_id ? String(r.telegram_chat_id) : null,
      telegram_ok: r.telegram_notifications_enabled !== false,
      dob: r.date_of_birth ? String(r.date_of_birth) : null,
    });
  }
  return out;
}

// Any job seeker (used only for test sends, so the 30-day / date filter is
// bypassed when an explicit test target is given).
async function loadTestRecipients(
  supabase: any,
  audience: Audience,
  testUserId?: string,
  testEmail?: string,
): Promise<Recipient[]> {
  let query = supabase
    .from("profiles")
    .select("user_id, full_name, email, telegram_chat_id, telegram_notifications_enabled, date_of_birth")
    .not("user_id", "is", null)
    .limit(5);
  if (testUserId) query = query.eq("user_id", testUserId);
  if (testEmail) query = query.ilike("email", testEmail);
  const { data } = await query;
  const rows = data ?? [];
  if (rows.length === 0) return [];

  let companies = new Map<string, any>();
  if (audience === "employer") {
    const { data: comp } = await supabase
      .from("companies")
      .select("user_id, company_name, email, telegram_chat_id, telegram_notifications_enabled")
      .in("user_id", rows.map((r: any) => String(r.user_id)));
    for (const c of comp ?? []) companies.set(String(c.user_id), c);
  }

  return rows.map((r: any) => {
    const c = companies.get(String(r.user_id));
    const useCompanyTelegram = Boolean(c?.telegram_chat_id);
    return {
      user_id: String(r.user_id),
      name: String(c?.company_name || r.full_name || "there").trim(),
      email: (c?.email || r.email) ? String(c?.email || r.email) : null,
      telegram_chat_id: (c?.telegram_chat_id || r.telegram_chat_id)
        ? String(c?.telegram_chat_id || r.telegram_chat_id)
        : null,
      telegram_ok: useCompanyTelegram
        ? c.telegram_notifications_enabled !== false
        : r.telegram_notifications_enabled !== false,
      dob: r.date_of_birth ? String(r.date_of_birth) : null,
    };
  });
}

async function deliver(
  supabase: any,
  recipient: Recipient,
  content: Composed,
  tpl: Templates,
  logType: string,
  emailBlocked: boolean,
  audience: Audience,
) {
  const channels: string[] = [];

  if (
    await safeInvoke(supabase, "email-api", {
      action: "send_push",
      user_id: recipient.user_id,
      title: content.pushTitle,
      message: content.pushBody,
      action_url: tpl.buttonUrl,
      type: "birthday",
      audience,
      // Email + Telegram are sent below with this side's own template, so the
      // push call must not fan out again.
      skip_fanout: true,
    })
  ) {
    channels.push("push");
  }

  if (recipient.telegram_chat_id && recipient.telegram_ok) {
    if (
      await safeInvoke(supabase, "email-api/telegram", {
        action: "send",
        // Each side goes out on its own bot: job seeker wish -> job seekers bot,
        // employer wish -> employers bot.
        audience,
        chat_id: recipient.telegram_chat_id,
        text: escapeHtml(content.telegramText),
        parse_mode: "HTML",
        button_text: tpl.buttonText || undefined,
        button_url: tpl.buttonText ? tpl.buttonUrl : undefined,
      })
    ) {
      channels.push("telegram");
    }
  }

  if (recipient.email && !emailBlocked) {
    // Template body me button already hai — extra button nahi jodte.
    if (
      await safeInvoke(supabase, "email-api/send-email", {
        to: recipient.email,
        toName: recipient.name,
        subject: content.emailSubject,
        htmlContent: content.emailHtml,

        templateMode: "complete",
        audience: audience === "employer" ? "employer" : "jobseeker",
      })
    ) {
      channels.push("email");
    }
  }

  if (channels.length > 0) {
    try {
      await supabase.from("marketing_notification_logs").insert({
        user_id: recipient.user_id,
        user_type: audience,
        notification_type: logType,
        channels_sent: channels,
        content_key: content.source,
      });
    } catch (e) {
      console.warn("[birthday] log insert failed:", e);
    }
  }
  return channels;
}

// ------------------------------------------------------------------ SERVE ---
export async function runBirthdayGreetings(supabase: any, body: any = {}) {
  const requestId = crypto.randomUUID().slice(0, 8);
  try {
    const today = String(body?.date || todayIST()).slice(0, 10);
    const previewOnly = body?.preview === true;
    const testUserId: string | undefined = body?.test_user_id;
    const testEmail: string | undefined = body?.test_email;
    const isTest = Boolean(testUserId || testEmail);
    const only = String(body?.audience || "").trim();
    const audiences: Audience[] = only === "job_seeker" || only === "employer"
      ? [only as Audience]
      : AUDIENCES;

    const totals = { push: 0, telegram: 0, email: 0 };
    const perAudience: Record<string, unknown> = {};
    let recipientsTotal = 0;
    let usersTotal = 0;
    const previews: unknown[] = [];

    for (const audience of audiences) {
      const tpl = await loadTemplates(supabase, audience);

      if (previewOnly && !isTest) {
        const content = await composeGreeting(tpl, String(body?.name || "Gohil Vishalbhai"), 23);
        perAudience[audience] = { preview: true, content };
        continue;
      }

      let recipients = isTest
        ? await loadTestRecipients(supabase, audience, testUserId, testEmail)
        : await loadBirthdayRecipients(supabase, today, audience);

      const logType = `birthday:${audience}:${today}`;

      // Skip anyone who already got this side's wish today.
      if (!isTest && recipients.length > 0) {
        const { data: already } = await supabase
          .from("marketing_notification_logs")
          .select("user_id")
          .eq("notification_type", logType);
        const sentTo = new Set((already ?? []).map((r: any) => String(r.user_id)));
        recipients = recipients.filter((r) => !sentTo.has(r.user_id));
      }

      if (recipients.length === 0) {
        perAudience[audience] = { recipients: 0, users_reached: 0 };
        continue;
      }

      const blockedEmails = isTest ? new Set<string>() : await optedOutEmails(supabase);
      const counts = { push: 0, telegram: 0, email: 0 };
      let sent = 0;

      for (let i = 0; i < recipients.length; i += BATCH_SIZE) {
        const batch = recipients.slice(i, i + BATCH_SIZE);
        const results = await Promise.allSettled(
          batch.map(async (r) => {
            const content = await composeGreeting(tpl, r.name, ageFrom(r.dob, today));
            if (previewOnly) {
              previews.push({ audience, user_id: r.user_id, name: r.name, content });
              return [] as string[];
            }
            return deliver(supabase, r, content, tpl, logType, blockedEmails.has(r.user_id), audience);
          }),
        );
        for (const res of results) {
          if (res.status !== "fulfilled" || res.value.length === 0) continue;
          sent++;
          for (const ch of res.value) counts[ch as keyof typeof counts]++;
        }
      }

      recipientsTotal += recipients.length;
      usersTotal += sent;
      totals.push += counts.push;
      totals.telegram += counts.telegram;
      totals.email += counts.email;
      perAudience[audience] = { recipients: recipients.length, users_reached: sent, ...counts };

      console.log(
        `[${requestId}] 🎂 ${today} ${audience}: recipients=${recipients.length} users=${sent} push=${counts.push} tg=${counts.telegram} mail=${counts.email}`,
      );
    }

    return {
      success: true,
      date: today,
      preview: previewOnly,
      recipients: recipientsTotal,
      users_reached: usersTotal,
      ...totals,
      by_audience: perAudience,
      ...(previewOnly && previews.length ? { previews } : {}),
    };
  } catch (error: any) {
    console.error(`[${requestId}] ❌`, error?.message || error);
    return { success: false, error: error?.message || String(error) };
  }
}
