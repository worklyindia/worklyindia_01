interface LoadingSpinnerProps {
  size?: 'sm' | 'md' | 'lg';
  className?: string;
}

export const LoadingSpinner = ({ size = 'md', className = '' }: LoadingSpinnerProps) => {
  const sizeClasses = {
    sm: 'w-3 h-3',
    md: 'w-4 h-4',
    lg: 'w-6 h-6'
  };

  return (
    <div className={`inline-block ${sizeClasses[size]} border-2 border-muted/30 border-t-primary rounded-full animate-spin ${className}`} />
  );
};

export default LoadingSpinner;